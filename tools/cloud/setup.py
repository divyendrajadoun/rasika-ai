"""Move Rasika onto the cloud: Supabase (database + storage), Upstash (job queue), Netlify (website).

Reads .env (the keys you already have) and .env.cloud (the 7 cloud values), then:
  1. writes .env.worker-cloud  — the worker on this PC, pointed at the cloud
  2. writes .env.netlify       — the website's runtime env, for `netlify env:import`
  3. creates the private storage bucket on Supabase (if it is missing)
  4. creates the tables (drizzle migrations) and turns on row-level security
  5. checks the queue answers

Run with the worker's Python:  apps/worker/.venv/Scripts/python.exe tools/cloud/setup.py [site_url]
Nothing secret is printed.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def read_env(p: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in p.read_text(encoding="utf8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        out[k.strip()] = v.strip().strip('"').strip("'")
    return out


def write_env(p: Path, values: dict[str, str], head: str) -> None:
    lines = [f"# {head}", "# generated by tools/cloud/setup.py — gitignored, never commit"]
    lines += [f"{k}={v}" for k, v in values.items() if v != ""]
    p.write_text("\n".join(lines) + "\n", encoding="utf8")


local = read_env(ROOT / ".env")
cloud = read_env(ROOT / ".env.cloud")
need = [
    "FILL_DATABASE_URL_POOLER",
    "FILL_DATABASE_URL_SESSION",
    "FILL_S3_ENDPOINT",
    "FILL_S3_REGION",
    "FILL_S3_ACCESS_KEY_ID",
    "FILL_S3_SECRET_ACCESS_KEY",
    "FILL_REDIS_URL",
]
missing = [k for k in need if not cloud.get(k)]
if missing:
    sys.exit("Fill these in .env.cloud first: " + ", ".join(k.removeprefix("FILL_") for k in missing))
for k in ("FILL_DATABASE_URL_POOLER", "FILL_DATABASE_URL_SESSION"):
    if "[YOUR-PASSWORD]" in cloud[k]:
        sys.exit(f"{k.removeprefix('FILL_')}: replace [YOUR-PASSWORD] with the database password")
if not cloud["FILL_REDIS_URL"].startswith("rediss://"):
    sys.exit("REDIS_URL should be the rediss:// (TLS) URL from Upstash")

site = (sys.argv[1] if len(sys.argv) > 1 else local.get("NEXT_PUBLIC_SITE_URL", "")).rstrip("/")
s3 = {
    "S3_ENDPOINT": cloud["FILL_S3_ENDPOINT"].rstrip("/"),
    "S3_PUBLIC_ENDPOINT": cloud["FILL_S3_ENDPOINT"].rstrip("/"),
    "S3_REGION": cloud["FILL_S3_REGION"],
    "S3_BUCKET": local.get("S3_BUCKET", "rasika"),
    "S3_ACCESS_KEY_ID": cloud["FILL_S3_ACCESS_KEY_ID"],
    "S3_SECRET_ACCESS_KEY": cloud["FILL_S3_SECRET_ACCESS_KEY"],
    "S3_FORCE_PATH_STYLE": "true",
}

# 1. the worker on this PC
worker = {
    **{k: v for k, v in local.items() if not k.startswith(("RASIKA_TEST_", "NEXT_PUBLIC_"))},
    **s3,
    "DATABASE_URL": cloud["FILL_DATABASE_URL_SESSION"],
    "REDIS_URL": cloud["FILL_REDIS_URL"],
    "WORKER_QUEUE_POLL_SEC": "30",
}
write_env(ROOT / ".env.worker-cloud", worker, "the worker on this PC, against Supabase + Upstash")

# 2. the website on Netlify (worker-only and local-only keys stay out)
WORKER_ONLY = ("WORKER_", "WHISPER_", "ENABLE_", "RASIKA_TEST_", "DEEPGRAM_")
web = {
    **{k: v for k, v in local.items() if not k.startswith(WORKER_ONLY) and k != "NODE_ENV"},
    **s3,
    "DATABASE_URL": cloud["FILL_DATABASE_URL_POOLER"],
    "DB_POOL_MAX": "3",
    "REDIS_URL": cloud["FILL_REDIS_URL"],
}
if site:
    web["SITE_URL"] = web["NEXT_PUBLIC_SITE_URL"] = site
write_env(ROOT / ".env.netlify", web, f"Netlify runtime env for {site or '(site url not set yet)'}")
print(f"wrote .env.worker-cloud ({len(worker)} keys) and .env.netlify ({len(web)} keys)")

# 3. storage bucket (private: every read and write is a signed URL)
import boto3  # noqa: E402
from botocore.config import Config  # noqa: E402

b3 = boto3.client(
    "s3",
    endpoint_url=s3["S3_ENDPOINT"],
    region_name=s3["S3_REGION"],
    aws_access_key_id=s3["S3_ACCESS_KEY_ID"],
    aws_secret_access_key=s3["S3_SECRET_ACCESS_KEY"],
    config=Config(s3={"addressing_style": "path"}, signature_version="s3v4"),
)
buckets = [b["Name"] for b in b3.list_buckets().get("Buckets", [])]
if s3["S3_BUCKET"] in buckets:
    print(f"storage: bucket '{s3['S3_BUCKET']}' already there")
else:
    b3.create_bucket(Bucket=s3["S3_BUCKET"])
    print(f"storage: created private bucket '{s3['S3_BUCKET']}'")
b3.put_object(Bucket=s3["S3_BUCKET"], Key="_setup/ping.txt", Body=b"ok")
b3.delete_object(Bucket=s3["S3_BUCKET"], Key="_setup/ping.txt")
print("storage: write + delete OK")

# 4. tables + row-level security
env = {**os.environ, "DATABASE_URL": cloud["FILL_DATABASE_URL_SESSION"], "RASIKA_CLOUD_BUILD": "1"}
subprocess.run(
    "npx drizzle-kit migrate", cwd=ROOT / "apps" / "web", env=env, check=True, shell=True
)
import psycopg  # noqa: E402

with psycopg.connect(cloud["FILL_DATABASE_URL_SESSION"], autocommit=True) as conn:
    conn.execute((ROOT / "apps/web/drizzle/0001_rls.sql").read_text(encoding="utf8"))
    rows = conn.execute(
        "select relname from pg_class c join pg_namespace n on n.oid=c.relnamespace "
        "where n.nspname='public' and c.relkind='r' and c.relrowsecurity order by 1"
    ).fetchall()
    print("database: tables ready; row-level security on:", ", ".join(r[0] for r in rows))

# 5. queue
import redis  # noqa: E402

r = redis.Redis.from_url(cloud["FILL_REDIS_URL"], socket_connect_timeout=5)
print("queue: Upstash answers", r.ping())
print("done")
